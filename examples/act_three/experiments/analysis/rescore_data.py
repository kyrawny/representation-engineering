"""
Assemble one tidy table of every generated text with its target and every available EPA measure.

measures (columns ``<m>_E``, ``<m>_P``, ``<m>_A``)
    orig   own reader on the full text, as logged at generation time (08 logs: original; revision logs: own_epa)
    own    own reader re-read on ``text500`` for ALL conditions (T5; plan G4)  -> use for cross-condition contrasts
    cross  the independent reader built on the *other* local model (Ministral for Llama texts, Llama for Ministral)
    m7b    Mistral-7B reader (E and A only; P is NaN)
    vader  VADER compound x 4.3 (E only), computed here on text500

``target_*`` is always the ACT target of the (scenario, pair) trial in experiment 08, whichever target the
condition itself was steered with (that is the paper's evaluation target).
"""
import json
from functools import lru_cache

import numpy as np
import pandas as pd

from .common import EXPERIMENTS_DIR, load_hybrid_raw
from .common import scenario_category as _cat_from_id  # noqa: F401

REV = EXPERIMENTS_DIR / "results" / "revision"
DIM = {"E": "evaluation", "P": "potency", "A": "activity"}
CROSS_READER = {"llama3": "ministral", "ministral": "llama3"}


def _read_jsonl(p):
    out = []
    if p.exists():
        for line in open(p, encoding="utf-8"):
            if line.strip():
                out.append(json.loads(line))
    return out


@lru_cache(maxsize=None)
def _rescore(reader: str) -> pd.DataFrame:
    rows = _read_jsonl(REV / f"rescore_{reader}.jsonl")
    if not rows:
        return pd.DataFrame(columns=["generator", "key", "E", "P", "A"])
    return pd.DataFrame(rows)[["generator", "key", "E", "P", "A"]]


def _vader(texts):
    from vaderSentiment.vaderSentiment import SentimentIntensityAnalyzer
    a = SentimentIntensityAnalyzer()
    return [a.polarity_scores(t)["compound"] * 4.3 for t in texts]


def build(gen: str, with_vader: bool = True) -> pd.DataFrame:
    """One row per (trial, condition) generated by model ``gen`` ('llama3' | 'ministral')."""
    raw = load_hybrid_raw(gen)
    tgt = {}
    rows = []
    for t in raw["trials"]:
        k = f"{t['scenario_id']}|{t['pair']}"
        tgt[k] = t["target_epa"]
        for cond, c in t["conditions"].items():
            rows.append({"key": f"{k}|{cond}", "scenario_id": t["scenario_id"], "pair": t["pair"],
                         "agent": t["agent_identity"], "user": t["user_identity"], "cond": cond, "source": "08",
                         "text500": c["text"][:500],
                         **{f"orig_{d}": c["epa"][DIM[d]] for d in "EPA"}})
    for p in sorted((REV / gen).glob("*.jsonl")):
        if "quick" in p.name or p.name.startswith(("16_", "18_")):
            continue
        for r in _read_jsonl(p):
            if not r.get("scenario_id") or r.get("text500") is None:
                continue
            e = r.get("own_epa") or {}
            rows.append({"key": r["key"], "scenario_id": r["scenario_id"], "pair": r["pair"], "agent": r["agent"],
                         "user": r["user"], "cond": r["condition"], "source": p.name, "text500": r["text500"],
                         **{f"orig_{d}": e.get(DIM[d], np.nan) for d in "EPA"}})
    df = pd.DataFrame(rows)
    for d in "EPA":
        df[f"target_{d}"] = [tgt[f"{s}|{p}"][DIM[d]] for s, p in zip(df.scenario_id, df.pair)]
    for name, reader in (("own", gen), ("cross", CROSS_READER[gen]), ("m7b", "mistral7b")):
        rs = _rescore(reader)
        rs = rs[rs.generator == gen].drop(columns="generator").drop_duplicates("key")
        rs = rs.rename(columns={d: f"{name}_{d}" for d in "EPA"})
        df = df.merge(rs, on="key", how="left")
    if with_vader:
        df["vader_E"] = _vader(df.text500.tolist())
    df["category"] = df.scenario_id.str.rsplit("_", n=1).str[0]
    return df


def trial_id(df: pd.DataFrame) -> pd.Series:
    return df.scenario_id + "|" + df.pair
