def human():
    d = load_json(OUT_DIR / "human_descriptives.json")["means"]
    clmm = load_json(OUT_DIR / "human_clmm.json")
    mixed = load_json(OUT_DIR / "human_mixed.json")
    ITEM = {"appropriate": "Appropriate", "natural": "Natural", "non_sycophantic": "NonSyc"}
    CN = {"unsteered": "Unst", "pe_only": "PE", "repe_only": "RepE", "hybrid": "Hybrid"}
    for it, lab in ITEM.items():
        for c, cn in CN.items():
            mac("Human", lab, cn, val=d[it][c], nd=2)
        r = clmm[it]
        mac("Clmm", lab, "LR", val=r["LR_chisq"], nd=1)
        put(cname("Clmm", lab, "P"), pstr(r["LR_p"]))
        put(cname("Clmm", lab, "Model"), "random participant slopes" if r["model_used"] == "random slopes" else "random intercepts")
        ct, cc = r["contrasts_holm"], r["contrasts_ci"]
        for i, row in enumerate(ct):
            a, b = [x.strip() for x in row["contrast"].split(" - ")]
            key = cname("Clmm", lab, CN[b], "Minus", CN[a])
            # emmeans reports (first - second); store as (second - first) i.e. later condition minus earlier
            est, lo, hi = -row["estimate"], -cc[i]["asymp.UCL"], -cc[i]["asymp.LCL"]
            mac(key, "Est", val=est, nd=2, sign=True)
            put(key + "Ci", ci(lo, hi))
            put(key + "P", pstr(row["p.value"]))
        mac("Lmm", lab, "IccPid", val=mixed["lmm"][it]["icc_pid"], nd=2)
        mac("Lmm", lab, "IccVig", val=mixed["lmm"][it]["icc_vig"], nd=2)
        mac("Human", lab, "Alpha", val=mixed["reliability"][it]["krippendorff_alpha_ordinal"], nd=2)
        pl = mixed["participant_level"][it]
        put(cname("Human", lab, "FriedmanP"), pstr(pl["friedman_p"]))
        for k, v in pl["pairwise"].items():
            a, b = k.split("-")[1], k.split("-")[0]
            put(cname("Human", lab, "Wilcoxon", CN[b], "Minus", CN[a], "Holm"), pstr(v["p_holm"]))
        orig = mixed["original_pooled"][it]
        mac("Orig", lab, "H", val=orig["H"], nd=1)
    # table: CLMM contrasts
    rows = [r"\begin{tabular}{llrcc}", r"\toprule", r"Item & Contrast & Log-odds & 95\% CI & Holm $p$ \\", r"\midrule"]
    for it, lab in ITEM.items():
        first = True
        for b, a in [("PE", "Unst"), ("RepE", "Unst"), ("Hybrid", "Unst")]:
            key = cname("Clmm", lab, b, "Minus", a)
            rows.append(f"{'' if not first else lab.replace('NonSyc', 'Non-syc.')} & {b} $-$ {a} & \\{key}Est & \\{key}Ci & \\{key}P \\\\")
            first = False
        rows.append(r"\midrule" if it != "non_sycophantic" else "")
    rows += [r"\bottomrule", r"\end{tabular}"]
    (GENERATED_DIR / "tab_human_clmm.tex").write_text("\n".join(r for r in rows if r) + "\n", encoding="utf-8")


def static_design():
    """Protocol facts, reader validity, CAA metadata and design variance decomposition."""
    rr = load_json(OUT_DIR / "revision_results.json")
    ag = rr["agreement"]
    rows = [r"\begin{tabular}{lcccccc}", r"\toprule",
            r"& \multicolumn{2}{c}{Llama-3.1-8B} & \multicolumn{2}{c}{Ministral-8B} & \multicolumn{2}{c}{Mistral-7B} \\",
            r"\cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(lr){6-7}",
            r"Dim. & $r$ & MAE & $r$ & MAE & $r$ & MAE \\", r"\midrule"]
    t1 = ag["table1_llama_source_01_reading_quality"]
    val = ag["reader_calibration_test"]
    for d, lab in (("evaluation", "E"), ("potency", "P"), ("activity", "A")):
        cells = [num(t1[d]["pearson_r"]), num(t1[d]["mae"])]
        for rd in ("ministral", "mistral7b"):
            v = val[rd][d]
            cells += [num(v["pearson"]) if v["pearson"] == v["pearson"] else "--", num(v["mae"]) if v["pearson"] == v["pearson"] else "--"]
        rows.append(f"{lab} & " + " & ".join(cells) + r" \\")
        mac("Reader", "Llama", lab, "R", val=t1[d]["pearson_r"])
        mac("Reader", "Ministral", lab, "R", val=val["ministral"][d]["pearson"])
        if val["mistral7b"][d]["pearson"] == val["mistral7b"][d]["pearson"]:
            mac("Reader", "MistralSeven", lab, "R", val=val["mistral7b"][d]["pearson"])
    rows += [r"\bottomrule", r"\end{tabular}"]
    (GENERATED_DIR / "tab_reading.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")
    mac("Vader", "CalR", val=ag["vader_calibration_E"]["r"], nd=2)
    mac("Vader", "CalMae", val=ag["vader_calibration_E"]["mae"], nd=2)
    des = load_json(OUT_DIR / "design_rationale.json")
    for d, lab in (("evaluation", "E"), ("potency", "P"), ("activity", "A")):
        v = des["target_variance"]["llama3"][d]
        put(cname("Design", "Rtwo", "Pair", lab), f"{100 * v['r2_pair']:.0f}\\%")
        put(cname("Design", "Rtwo", "Scn", lab), f"{100 * v['r2_scenario']:.0f}\\%")
    put("ScenarioProvenance", r"\textbf{[AUTHORS: state here how the 100 scenarios were produced; the repository does not record it.]}")
    sc = rr["n_texts"]["llama3"]["by_cond"]
    meta = load_json(REV / "llama3" / "caa_meta.json")
    put("CaaLayer", str(meta["chosen_layer0"] + 1))
    put("CaaMult", num(meta["chosen_multiplier"], 1))
    put("CaaNExtract", str(meta["n_extract"]))
    put("CaaNHeld", str(meta["n_heldout"]))
    mac("Caa", "Norm", val=meta["caa_perturbation_l2"], nd=1)
    mac("Act", "Norm", val=meta["act_repe_perturbation"]["mean_sum_layer_norm"], nd=1)
    mac("Caa", "Heldout", "Base", val=meta["heldout_baseline_logit_diff"], nd=2)
    lay = meta["layer_candidates"][str(meta["chosen_layer0"])]
    mac("Caa", "Heldout", "Steered", val=lay["mean_logit_diff_steered"], nd=2)
    n_sc = len({k.split("|")[0] for k in _read_keys(REV / "llama3" / "15_sycophancy_baselines.jsonl")}) if (REV / "llama3" / "15_sycophancy_baselines.jsonl").exists() else 0
    put("SubsetScenarios", str(n_sc))
    put("SubsetTrials", f"{n_sc * 13:,}")
    rp = load_json(REV / "llama3" / "00_repro_check_ortho_on.json")
    put("ReproIdentical", str(rp["n_identical"]))
    put("ReproTotal", str(rp["n_texts"]))
    put("ReproTrials", str(rp["n_trials"]))
    put("MtConvs", "100")
    put("AysItems", "200")


def _read_keys(p):
    return [json.loads(l)["key"] for l in open(p, encoding="utf-8") if l.strip()]


def main():
    human()
    static_design()
    from . import make_results_tables
    make_results_tables.build(mac, put, cname, num, ci, pstr)
    make_results_tables.more(mac, put, cname, num, ci, pstr)
    make_results_tables.ablation_extra(mac, put, cname, num, ci, pstr)
    make_results_tables.per_dim(mac, put, cname, num, ci, pstr)
    make_results_tables.per_dim_table(num)
    make_results_tables.multiturn_extra(mac, put, cname, num, ci, pstr)
    make_results_tables.legacy_appendix(mac, put, cname, num, ci, pstr)
    write()
    print(f"{len(M)} macros written")


if __name__ == "__main__":
    main()
