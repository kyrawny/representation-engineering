import json
import math
import re

from .common import GENERATED_DIR, OUT_DIR, REPO_ROOT, ensure_dirs, load_json

REV = REPO_ROOT / "examples" / "act_three" / "experiments" / "results" / "revision"
_DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]
M: dict = {}


def cname(*parts) -> str:
    out = []
    for p in parts:
        p = re.sub(r"[^A-Za-z0-9]+", "", str(p))
        out.append(p[:1].upper() + p[1:])
    s = "".join(out)
    return "".join(_DIGITS[int(ch)] if ch.isdigit() else ch for ch in s)


def put(name: str, val: str) -> None:
    assert name not in M, f"duplicate macro {name}"
    M[name] = val


def num(x, nd=3, sign=False) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return s.replace("-", "$-$") if s.startswith("-") else (s.replace("+", "$+$") if s.startswith("+") else s)


def pstr(p) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "n/a"
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}"


def mac(*parts, val, nd=3, sign=False):
    put(cname(*parts), num(val, nd, sign) if not isinstance(val, str) else val)


def ci(lo, hi, nd=2) -> str:
    return f"[{num(lo, nd)}, {num(hi, nd)}]"


def write():
    ensure_dirs()
    lines = ["% AUTO-GENERATED by analysis/make_revision_tables.py -- do not edit by hand."]
    for k in sorted(M):
        lines.append(f"\\newcommand{{\\{k}}}{{{M[k]}}}")
    (GENERATED_DIR / "macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


