"""
Design documentation (plan T11): scenario categories, identity pairs, target variance decomposition.
Writes results/analysis/design_rationale.json, results/analysis/design_rationale.md and
paper/generated/tab_design.tex.   python -m examples.act_three.experiments.analysis.design_rationale
"""
import numpy as np
import pandas as pd

from ..config import IDENTITY_PAIRS
from ..scenarios import SCENARIOS
from .common import GENERATED_DIR, OUT_DIR, ensure_dirs, load_hybrid_raw, load_json, save_json

CAT_LABEL = {"pos_e": "positive E", "neg_e": "negative E", "high_p": "high P", "low_p": "low P",
             "high_a": "high A", "low_a": "low A", "mixed": "mixed / neutral"}
REPEATED = {"counselor_client": "client_counselor", "boss_subordinate": "subordinate_boss",
            "teacher_student": "student_teacher", "doctor_patient": "patient_doctor",
            "mother_daughter": "daughter_mother", "receptionist_visitor": "visitor_receptionist"}


def run():
    ensure_dirs()
    raw = load_hybrid_raw("llama3")["trials"]
    read = {}
    pairs = {}
    for t in raw:
        read[t["scenario_id"]] = t["user_statement_epa"]
        pairs[t["pair"]] = (t["agent_identity"], t["user_identity"], t["agent_identity_epa"], t["user_identity_epa"])
    sc = pd.DataFrame([{"id": s["id"], "cat": s["category"], "text": s["text"],
                        **{k[0].upper(): read[s["id"]][k] for k in ("evaluation", "potency", "activity")}} for s in SCENARIOS])
    cats = []
    for c, g in sc.groupby("cat"):
        cats.append({"category": c, "label": CAT_LABEL[c], "n": int(len(g)),
                     "mean_read_E": float(g.E.mean()), "mean_read_P": float(g.P.mean()), "mean_read_A": float(g.A.mean()),
                     "examples": g.text.head(2).tolist()})
    cats.sort(key=lambda x: list(CAT_LABEL).index(x["category"]))
    ident = []
    for name, a, u in IDENTITY_PAIRS:
        _, _, ae, ue = pairs[name]
        ident.append({"pair": name, "agent": a, "user": u, "agent_epa": [ae[k] for k in ("evaluation", "potency", "activity")],
                      "user_epa": [ue[k] for k in ("evaluation", "potency", "activity")],
                      "role_reversed_with": REPEATED.get(name) or next((k for k, v in REPEATED.items() if v == name), None)})
    at = load_json(OUT_DIR / "act_targets.json")
    dec = {m: {d: {"r2_pair": at[m]["target_distribution"][d]["r2_pair"], "r2_scenario": at[m]["target_distribution"][d]["r2_scenario"],
                   "sd": at[m]["target_distribution"][d]["sd"]} for d in ("evaluation", "potency", "activity")}
           for m in ("llama3", "ministral")}
    res = {"categories": cats, "n_scenarios": len(sc), "identity_pairs": ident, "target_variance": dec,
           "role_swap_differences": at["llama3"]["role_swap_differences"],
           "scenario_provenance": "NOT RECORDED in the repository (single commit, no generation script or note); authors must confirm."}
    save_json(res, "design_rationale.json")

    L = ["# Design rationale (generated by analysis/design_rationale.py)", "",
         f"## Scenarios ({len(sc)} in {len(cats)} categories)", "",
         "| category | n | mean read E | P | A | examples |", "|---|---|---|---|---|---|"]
    for c in cats:
        L.append(f"| {c['label']} | {c['n']} | {c['mean_read_E']:.2f} | {c['mean_read_P']:.2f} | {c['mean_read_A']:.2f} | "
                 f"\"{c['examples'][0]}\"; \"{c['examples'][1]}\" |")
    L += ["", "Mean read EPA is the Llama reader's reading of the user message (experiment 08 logs).", "",
          "Provenance of the scenarios: **not recorded in the repository**; see BLOCKERS.md. The authors must state it.", "",
          "## Identity pairs (13)", "", "| pair | agent EPA | user EPA | role-reversed counterpart |", "|---|---|---|---|"]
    for i in ident:
        L.append(f"| {i['pair']} | {', '.join(f'{x:.2f}' for x in i['agent_epa'])} | {', '.join(f'{x:.2f}' for x in i['user_epa'])} | {i['role_reversed_with'] or 'symmetric'} |")
    L += ["", "Rationale: 6 role-reversed pairs hold the relationship constant while flipping status, so ACT's prediction of "
          "opposite Potency can be tested; 1 symmetric pair (friend-friend); pairs common in human-AI deployment (counselling, teaching, medicine, service).", "",
          "## Variance of ACT targets explained", "", "| model | dim | R2 pair | R2 scenario | SD |", "|---|---|---|---|---|"]
    for m, v in dec.items():
        for d, x in v.items():
            L.append(f"| {m} | {d[0].upper()} | {x['r2_pair']:.2f} | {x['r2_scenario']:.2f} | {x['sd']:.2f} |")
    (OUT_DIR / "design_rationale.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    T = [r"\begin{tabular}{lrrrr}", r"\toprule", r"Category & $n$ & $\bar E$ & $\bar P$ & $\bar A$ \\", r"\midrule"]
    for c in cats:
        T.append(f"{c['label']} & {c['n']} & {c['mean_read_E']:.2f} & {c['mean_read_P']:.2f} & {c['mean_read_A']:.2f} \\\\")
    T += [r"\bottomrule", r"\end{tabular}"]
    (GENERATED_DIR / "tab_design_scenarios.tex").write_text("\n".join(T) + "\n", encoding="utf-8")
    T = [r"\begin{tabular}{llccc}", r"\toprule", r"Agent & User & Agent EPA & User EPA & Role-reversed \\", r"\midrule"]
    for i in ident:
        T.append(f"{i['agent']} & {i['user']} & ({', '.join(f'{x:.1f}' for x in i['agent_epa'])}) & "
                 f"({', '.join(f'{x:.1f}' for x in i['user_epa'])}) & {'yes' if i['role_reversed_with'] else 'symmetric'} \\\\")
    T += [r"\bottomrule", r"\end{tabular}"]
    (GENERATED_DIR / "tab_design_pairs.tex").write_text("\n".join(T) + "\n", encoding="utf-8")
    return res


if __name__ == "__main__":
    r = run()
    print("categories", [(c["category"], c["n"]) for c in r["categories"]])
